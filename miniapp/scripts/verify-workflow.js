const {chromium, expect} = require('@playwright/test');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({headless: true});
  const page = await browser.newPage({viewport: {width: 390, height: 844}});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:18082/preview/');
  await page.locator('[data-action="water"]').click();
  const pending = page.waitForResponse(response => response.url().endsWith('/water') && response.request().method() === 'POST');
  await page.locator('#water-form button[type="submit"]').click();
  const created = await pending;
  expect(created.status()).toBe(202);
  expect((await created.json()).status).toBe('pending');
  await expect(page.locator('#command-status')).toHaveText('补水完成', {timeout: 20000});
  await page.screenshot({path: '../evidence/stage8-browser-command.png', fullPage: true});
  await page.locator('nav [data-tab="care"]').click();
  await page.locator('[data-action="research"]').click();
  await expect(page.locator('[data-action="confirm-care"]')).toBeEnabled({timeout: 20000});
  await page.locator('[data-action="confirm-care"]').click();
  await expect(page.locator('#care-validity')).toContainText('养护卡已确认');
  await expect(page.locator('[data-action="confirm-care"]')).toBeDisabled();
  await page.locator('nav [data-tab="memories"]').click();
  const name = '浏览器验证记忆 ' + Date.now();
  await page.locator('[name="title"]').fill(name);
  await page.locator('[name="story"]').fill('这是明确标注的模拟验收故事。');
  await page.locator('[name="experience"]').fill('傍晚少量浇水');
  await page.locator('#memory-form button[type="submit"]').click();
  const item = page.locator('article.memory').filter({hasText: name});
  await item.locator('[data-action="structure"]').click();
  await expect(item.locator('input[type="checkbox"]')).toBeVisible({timeout: 20000});
  await item.locator('input[type="checkbox"]').check();
  await expect(item.locator('input[type="checkbox"]')).toBeChecked();
  await page.locator('nav [data-tab="home"]').click();
  await page.locator('#auto-switch').check();
  await expect(page.locator('#auto-switch')).toBeChecked();
  await page.locator('#auto-switch').uncheck();
  await expect(page.locator('#error')).toBeHidden();
  expect(errors).toEqual([]);
  fs.writeFileSync('../evidence/stage8-browser-workflow.json', JSON.stringify({source_type: 'mock', pending: 'PASS', succeeded: 'PASS', care_confirmation: 'PASS', memory_rule: 'PASS', auto_switch: 'PASS', errors}, null, 2));
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
